// 取某模块某阶的章节数组
function getChapters(module, level) {
  return (CURRICULUM[module] && CURRICULUM[module].levels[level])
    ? CURRICULUM[module].levels[level].chapters : [];
}
// 统计总章节数（用于进度文案）
function totalChapters() {
  let n = 0;
  CURRICULUM_ORDER.forEach(m => {
    ["L1","L2","L3"].forEach(l => { n += getChapters(m, l).length; });
  });
  return n;
}
