// 分阶竞赛拓展课程 (R3)：尖端班/集训队，优先匹配奥数向板块
const XUEERSI_ADV_BY_LEVEL = {"L1": "ADV-L1", "L2": "ADV-L2", "L3": "ADV-L3"};
// 奥数向板块 (R3)：优先匹配 advanced 课程
const XUEERSI_ADV_BOARDS = ["view", "rule", "numtheory", "reason", "count", "strategy"];

const XUEERSI_MAP = {};
XUEERSI_COURSES.forEach(function(c){ XUEERSI_MAP[c.id] = c; });

/* 给定知识树节点 (module, boardId, level, topic)，返回其对标的学而思课程。
   匹配逻辑：R1 年级→分阶；R2 科目→四模块；R3 班型→难度；
   R4 若板块属奥数向(ADV_BOARDS)且存在 advanced 课程，则取 advanced。 */
function getXueersiCourse(module, boardId, level, topic) {
  if (!level || !XUEERSI_REP_BY_LEVEL[level]) return null;
  var useAdv = XUEERSI_ADV_BOARDS.indexOf(boardId) >= 0 && XUEERSI_ADV_BY_LEVEL[level];
  var cid = useAdv ? XUEERSI_ADV_BY_LEVEL[level] : XUEERSI_REP_BY_LEVEL[level];
  var c = XUEERSI_MAP[cid];
  if (!c) return null;
  return {
    course: c,
    matchType: useAdv ? 'advanced' : 'standard',
    rationale: useAdv
      ? '竞赛拓展对标：' + c.classType + '（奥数七大模块/竞赛专题加深），对应 ' + level
      : '标准对标：' + c.classType + '（数学思维全年班），覆盖 ' + module + '/' + (boardId||'') + ' 于 ' + level
  };
}

// 取某分阶的全部对标课程（含标准 + 竞赛拓展）
function getXueersiCoursesForLevel(level) {
  var ids = [];
  if (XUEERSI_REP_BY_LEVEL[level]) ids.push(XUEERSI_REP_BY_LEVEL[level]);
  if (XUEERSI_ADV_BY_LEVEL[level]) ids.push(XUEERSI_ADV_BY_LEVEL[level]);
  return ids.map(function(id){ return XUEERSI_MAP[id]; }).filter(Boolean);
}

if (typeof window !== 'undefined') {
  window.XUEERSI_COURSES = XUEERSI_COURSES;
  window.getXueersiCourse = getXueersiCourse;
  window.getXueersiCoursesForLevel = getXueersiCoursesForLevel;
}
