/* 扁平索引：key = `${module}:${boardId}:${level}:${topic}` */
const FRAMEWORK_COURSE_MAP = {};
Object.keys(FRAMEWORK_COURSES).forEach(function(k){
  const parts = k.split(":");
  const module = parts[0], boardId = parts[1];
  const c = FRAMEWORK_COURSES[k];
  Object.keys(c.topics).forEach(function(topic){
    ["L1","L2","L3"].forEach(function(level){
      FRAMEWORK_COURSE_MAP[module+":"+boardId+":"+level+":"+topic] = c;
    });
  });
});

/* 取某个知识树叶子节点对应的学而思课程 */
function getFrameworkCourse(module, boardId, level, topic){
  const c = FRAMEWORK_COURSES[module+":"+boardId];
  if(!c) return null;
  const summary = (c.topics && c.topics[topic]) ? c.topics[topic] : c.summary;
  return {
    platform: c.platform,
    title: c.title,
    url: c.url,
    board: c.board,
    level: level,
    topic: topic,
    summary: summary
  };
}
